#!/usr/bin/env python3
"""Aggregate legal notices from the exact release artifacts in Gradle's inventory.

No network requests; no execution of dependency code. Source texts are retained verbatim
apart from UTF-8 decoding, and each entry records the artifact and document SHA-256.
Missing bundled notices are reported explicitly, never replaced with invented attribution.
"""
import argparse
import csv
import hashlib
import io
import json
import os
from pathlib import Path
import re
import zipfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
LEGAL_NAME = re.compile(r"(?:^|/)(?:license|notice|copying)(?:[._-].*)?$", re.IGNORECASE)
GENERATED = "Third-party notices extracted from pinned release artifacts.\n"


def sha(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def documents(archive, prefix="", depth=0):
    found = []
    for info in archive.infolist():
        if info.is_dir():
            continue
        if LEGAL_NAME.search(info.filename) and info.file_size <= 512 * 1024:
            content = archive.read(info)
            try:
                text = content.decode("utf-8")
            except UnicodeDecodeError:
                continue
            found.append({"entry": prefix + info.filename,
                          "sha256": hashlib.sha256(content).hexdigest(), "text": text})
        elif depth < 1 and info.filename == "classes.jar":
            with zipfile.ZipFile(io.BytesIO(archive.read(info))) as nested:
                found.extend(documents(nested, prefix + "classes.jar!", depth + 1))
    return found


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inventory", type=Path, default=ROOT / "app/build/reports/dependency-inventory.tsv")
    parser.add_argument("--cache", type=Path, default=Path(os.environ.get("GRADLE_USER_HOME", str(Path.home() / ".gradle"))) / "caches/modules-2/files-2.1")
    args = parser.parse_args()
    with args.inventory.open(newline="") as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    records = []
    chunks = [GENERATED,
              "See AGPL-3.0.txt for this project's license; other components retain their own licenses.\n",
              "This collects bundled legal files, not an independent copyright or license audit.\n"]
    for row in rows:
        group, artifact, version = row["coordinate"].split(":", 2)
        if artifact == "protocol" and version == "unspecified":
            records.append({**row, "status": "local-project-AGPL-3.0", "legalEntries": []})
            continue
        base = args.cache / group / artifact / version
        paths = list(base.glob("*/" + row["filename"]))
        paths = [path for path in paths if sha(path) == row["sha256"]]
        if len(paths) != 1:
            raise SystemExit(f"Expected one exact cached artifact for {row['coordinate']}, found {len(paths)}")
        with zipfile.ZipFile(paths[0]) as archive:
            docs = documents(archive)
        poms = list(base.glob("*/*.pom"))
        metadata = {}
        if len(poms) == 1:
            pom = ET.parse(poms[0]).getroot()
            ns = {"m": "http://maven.apache.org/POM/4.0.0"}
            metadata = {
                "pomSha256": sha(poms[0]),
                "projectUrl": pom.findtext("m:url", default="", namespaces=ns),
                "licenses": [{"name": item.findtext("m:name", default="", namespaces=ns),
                              "url": item.findtext("m:url", default="", namespaces=ns)}
                             for item in pom.findall("m:licenses/m:license", ns)],
            }
        records.append({**row, **metadata, "status": "bundled-notices-extracted" if docs else "no-bundled-legal-text",
                        "legalEntries": [{key: value for key, value in doc.items() if key != "text"} for doc in docs]})
        chunks.append("\n" + "=" * 72 + "\n" + row["coordinate"] + "\nArtifact SHA-256: " + row["sha256"] + "\n")
        for license in metadata.get("licenses", []):
            chunks.append("POM license: " + license["name"] + " " + license["url"] + "\n")
        if metadata.get("projectUrl"):
            chunks.append("Project: " + metadata["projectUrl"] + "\n")
        if not docs:
            chunks.append("No LICENSE/NOTICE/COPYING text found in this artifact. See dependency metadata and project notices.\n")
        for doc in docs:
            chunks.append("\n--- " + doc["entry"] + " ---\n" + doc["text"] + "\n")
    legal = ROOT / "app/src/main/assets/legal/Third-party-artifact-notices.txt"
    if legal.exists() and not legal.read_text().startswith(GENERATED):
        raise SystemExit("Refusing to overwrite a document not generated by this script")
    legal.write_text("".join(chunks))
    report = ROOT / "docs/dependency-artifacts.json"
    report.write_text(json.dumps({"scope": "releaseRuntimeClasspath", "artifacts": records,
                                  "note": "Archive notices only; missing notices require metadata/source review."}, indent=2) + "\n")
    missing = [row["coordinate"] for row in records if row["status"] == "no-bundled-legal-text"]
    print(json.dumps({"artifactCount": len(records), "withBundledNotices": sum(bool(r["legalEntries"]) for r in records),
                      "withoutBundledNotices": missing, "legalAsset": str(legal), "report": str(report)}, indent=2))
