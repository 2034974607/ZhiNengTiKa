#!/usr/bin/env python3
"""Collect additional Debug/UI-test notices from pinned runtime locks and cached archives.

This supplements the resolved Release inventory; it is not a packaged-class inventory.
It does not change app assets or APKs, download dependencies, or execute dependency code.
"""
import argparse
import json
import os
from pathlib import Path
import runpy
import xml.etree.ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parent.parent
HEADER = "Additional Debug and Android instrumentation test dependency notices.\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cache", type=Path, default=Path(os.environ.get("GRADLE_USER_HOME", str(Path.home() / ".gradle"))) / "caches/modules-2/files-2.1")
    args = parser.parse_args()
    helper = runpy.run_path(str(ROOT / "tools/collect-dependency-notices.py"))
    documents, sha = helper["documents"], helper["sha"]
    scopes = {"debugRuntimeClasspath", "debugAndroidTestRuntimeClasspath"}
    records, chunks = [], [HEADER, "Selected from app/gradle.lockfile, excluding Release runtime coordinates.\n",
                           "Cached artifact and legal document hashes are recorded in debug-test-artifacts.json.\n",
                           "Other components retain their original licenses. Missing archive texts are explicit.\n"]
    for line in (ROOT / "app/gradle.lockfile").read_text().splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        coordinate, configurations = line.split("=", 1)
        configurations = set(configurations.split(","))
        if not configurations.intersection(scopes) or "releaseRuntimeClasspath" in configurations:
            continue
        group, artifact, version = coordinate.split(":", 2)
        base = args.cache / group / artifact / version
        binaries = sorted(path for path in base.glob("*/*")
                          if path.is_file() and path.suffix in {".jar", ".aar"}
                          and not path.name.endswith(("-sources.jar", "-javadoc.jar")))
        poms = sorted(base.glob("*/*.pom"))
        record = {"coordinate": coordinate, "runtimeScopes": sorted(configurations.intersection(scopes)), "artifacts": []}
        chunks.append("\n" + "=" * 72 + "\n" + coordinate + "\n")
        if len(poms) == 1:
            ns = {"m": "http://maven.apache.org/POM/4.0.0"}
            pom = ET.parse(poms[0]).getroot()
            licenses = [{"name": item.findtext("m:name", default="", namespaces=ns), "url": item.findtext("m:url", default="", namespaces=ns)} for item in pom.findall("m:licenses/m:license", ns)]
            record.update({"pomSha256": sha(poms[0]), "licenses": licenses})
            for license in licenses:
                chunks.append("POM license: " + license["name"] + " " + license["url"] + "\n")
        for binary in binaries:
            with zipfile.ZipFile(binary) as archive:
                legal = documents(archive)
            digest = sha(binary)
            record["artifacts"].append({"filename": binary.name, "sha256": digest, "legalEntries": [{key: value for key, value in item.items() if key != "text"} for item in legal]})
            chunks.append("Artifact: " + binary.name + "\nSHA-256: " + digest + "\n")
            if not legal:
                chunks.append("No bundled LICENSE/NOTICE/COPYING text found; consult POM and upstream source.\n")
            for item in legal:
                chunks.append("\n--- " + item["entry"] + " ---\n" + item["text"] + "\n")
        if not binaries:
            chunks.append("No cached matching JAR/AAR; metadata/variant coordinate only in this supplement.\n")
        records.append(record)
    notice = ROOT / "docs/debug-test-notices.txt"
    if notice.exists() and not notice.read_text().startswith(HEADER):
        raise SystemExit("Refusing to overwrite a notice not generated by this script")
    notice.write_text("".join(chunks))
    report = ROOT / "docs/debug-test-artifacts.json"
    report.write_text(json.dumps({"scope": "Additional pinned Debug/UI-test runtime coordinates absent from Release runtime", "notPackagedClassInventory": True, "artifacts": records}, indent=2) + "\n")
    assert all(any(item["legalEntries"] for item in record["artifacts"]) for record in records if record["coordinate"].startswith("org.hamcrest:"))
    print(json.dumps({"additionalCoordinates": len(records), "cachedBinaryCount": sum(len(record["artifacts"]) for record in records), "notice": str(notice), "report": str(report)}, indent=2))


if __name__ == "__main__":
    main()
